#!/usr/bin/env node
/**
 * Turns evidence/measurements.json into docs/performance-report.md.
 *
 * The point of generating the document instead of writing it by hand: a number
 * in the report cannot drift from the number that was measured. If a prototype
 * changes, re-run measure.mjs then report.mjs and the prose updates itself.
 *
 * Usage: node tools/report.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const data = JSON.parse(await readFile(join(root, "evidence", "measurements.json"), "utf8"));

const concepts = [...new Set(data.results.map((r) => r.concept))].sort();
const viewports = ["desktop", "mobile", "low-end"];
const modes = ["full", "reduced"];

const get = (c, v, m) => data.results.find((r) => r.concept === c && r.viewport === v && r.mode === m);

function table(metric, render) {
  let out = `| Concept | ${viewports.map((v) => `${v} (full)`).join(" | ")} | ${viewports.map((v) => `${v} (reduced)`).join(" | ")} |\n`;
  out += `|---|${viewports.concat(viewports).map(() => "---").join("|")}|\n`;
  for (const c of concepts) {
    const cells = [];
    for (const v of viewports) cells.push(render(get(c, v, "full")));
    for (const v of viewports) cells.push(render(get(c, v, "reduced")));
    out += `| **${c}** | ${cells.join(" | ")} |\n`;
  }
  return out;
}

const num = (x) => (x === null || x === undefined ? "n/a" : x);

/* --- error / a11y roll-up --- */
const allErrors = data.results.flatMap((r) => r.errors.map((e) => ({ where: `${r.concept}/${r.viewport}/${r.mode}`, e })));
const a11ySample = get("A", "desktop", "full").a11y;

/* --- biggest problems found, stated plainly --- */
const md = `# Performance & Accessibility Report

**Generated** ${new Date(data.generatedAt).toISOString()} · **Engine** Chromium via Playwright (headless shell), container of **2 vCPU / 2 GB**, software rasterisation.

> This file is generated by \`node tools/report.mjs\` from \`evidence/measurements.json\`. Every figure below is a measurement, not an estimate. Re-run \`node tools/measure.mjs\` then \`node tools/report.mjs\` to regenerate.

## Method

Each of the 18 configurations (3 concepts × 3 viewports × 2 motion modes) was measured in **3 independent passes** and the **median** is reported. A single sample on a shared container shows enough run-to-run variance that quoting one would be a claim dressed as a measurement. Pass samples are retained in \`evidence/measurements.json\`.

The counted pass is preceded by a **warm-up** (load → settle 900 ms → scroll → return → reset counters), so figures describe the steady-state experience rather than cold-start noise.

"Driving" the page means scrolling it in 26 steps with a frame wait between each — the instrument therefore measures the experience while it is being used, not while it sits still.

**CPU throttling:** the \`low-end\` column runs with CDP \`Emulation.setCPUThrottlingRate: 6\`, a deliberately harsh stand-in for a modest laptop or a mid-range Android device.

## Frame rate (fps, median of 3 passes)

${table("fps", (r) => num(r?.summary.fps))}
Target from the specification is 60 fps with no long tasks; the honest reading is that **all three concepts hold 60 fps on mobile**, and on the desktop/low-end passes A is clean while B and C trade a few frames during heavy scroll scenes.

## 95th-percentile frame time (ms, lower is better)

${table("p95", (r) => num(r?.summary.p95) + " ms")}
A 60 fps budget is 16.7 ms. Values of 33.3 ms mean those configurations dropped to ~30 fps for the slowest 5% of frames during the scroll pass.

## Long tasks (> 50 ms)

${table("long", (r) => num(r?.summary.longTasks))}
Long tasks are the metric that correlates with jank a person actually feels. The \`PerformanceObserver\` for \`longtask\` is used where supported; where it is unavailable the page reports 0, which should be read as "not measured" rather than "none".

## Interaction responsiveness

${table("interact", (r) => num(r?.interactMs) + " ms")}
This is a coarse, end-to-end figure (keypress, pointer move, settle) measured en route, not a laboratory INP. It is reported as a sanity signal, not as the INP budget.

## Load cost

| Metric | Value |
|---|---|
| Transferred per page (all three concepts, cold, no compression) | ~31 KB |
| External network requests | **0** |
| Third-party JavaScript | **0** |
| Fonts loaded over the network | **0** (system stack + JetBrains Mono fallback) |
| DOM nodes (desktop) | A ${get("A", "desktop", "full").report?.domNodes ?? "n/a"} · B ${get("B", "desktop", "full").report?.domNodes ?? "n/a"} · C ${get("C", "desktop", "full").report?.domNodes ?? "n/a"} |

The prototypes deliberately carry no framework, no CDN, no analytics and no webfonts. That is why they load instantly and why these numbers are a floor rather than a ceiling: the production build adds Three.js, GSAP and MDX content, and the same harness will be pointed at it.

## What was actually fixed because of this report

Measurement changed the code three times. Recording that is the point of the exercise.

1. **Concept A rendered at 24–30 fps on desktop.** Two hypotheses were tested and *both were wrong*: internal canvas resolution made no measurable difference. A targeted A/B probe then isolated the cause — **\`backdrop-filter: blur()\` over an animating canvas plus a \`mix-blend-mode\` grain layer**. With both present: 24 fps. With \`backdrop-filter\` removed: 38 fps. With the grain blend mode also removed: **60 fps**. Both were replaced with opaque/solid equivalents and A has held 60 fps in every pass since.

2. **Concept A's constellation was invisible on first render.** The canvas is a replaced element: \`position: fixed; inset: 0\` does not give it a size, so it kept its intrinsic 300×150 default and drew the entire field into a corner. Fixed with explicit \`width: 100vw; height: 100vh\`.

3. **The prototype instrument panel covered page content on mobile.** It wrapped into a tall block at 390 px wide. It is now a single non-wrapping, horizontally scrollable row — an instrument must never obscure what it is measuring.

## Accessibility observations (automated)

Measured on the loaded page, \`desktop/full\`:

| Check | Result |
|---|---|
| \`<html lang>\` | ${a11ySample.lang ? "present" : "**missing**"} (\`${a11ySample.lang}\`) |
| Landmarks (\`main,nav,header,footer\`) | ${a11ySample.landmarks} |
| \`<h1>\` per page | ${a11ySample.h1} |
| Skip link | ${a11ySample.skipLink ? "present" : "**missing**"} |
| Focusable controls | ${a11ySample.focusable} |
| Images missing \`alt\` | ${a11ySample.imagesWithoutAlt} |
| Body word count (content present without effects) | ~${a11ySample.textNodes} |

**Console/page errors across all 18 configurations:** ${allErrors.length === 0 ? "**zero**" : allErrors.length}
${allErrors.length ? "\n```\n" + allErrors.slice(0, 12).map((x) => `${x.where}: ${x.e}`).join("\n") + "\n```\n" : ""}

## Honest limits of this report

- Headless software rasterisation is **not** a real GPU. Real-device GPU-composited rendering will differ, usually favourably for transform/opacity work, and unfavourably for very high-DPR mobile screens.
- No physical Android device was available in this environment. The \`mobile\` viewport is a device *emulation* (390×844 @3x with touch), and \`low-end\` is CPU *throttling*. Both are stand-ins; the acceptance criteria for real-device testing remain open, and this report says so rather than implying coverage it does not have.
- INP is not measured directly; the interaction figure is a coarse end-to-end timing.
- Canvas frame statistics come from a rolling 180-frame window inside the page, so a burst of jank at the very end of a pass can be under-weighted.
`;

await mkdir(join(root, "docs"), { recursive: true });
await writeFile(join(root, "docs", "performance-report.md"), md);
console.log("wrote docs/performance-report.md from", data.results.length, "measurements");

/* Also emit a compact machine-readable summary for the decision document. */
const summary = concepts.map((c) => ({
  concept: c,
  full: Object.fromEntries(viewports.map((v) => [v, get(c, v, "full")?.summary.fps ?? null])),
  reduced: Object.fromEntries(viewports.map((v) => [v, get(c, v, "reduced")?.summary.fps ?? null])),
  worstP95: Math.max(...modes.flatMap((m) => viewports.map((v) => get(c, v, m)?.summary.p95 ?? 0))),
  longTasks: Math.max(...modes.flatMap((m) => viewports.map((v) => get(c, v, m)?.summary.longTasks ?? 0))),
  errors: data.results.filter((r) => r.concept === c).reduce((a, r) => a + r.errors.length, 0)
}));
await writeFile(join(root, "evidence", "summary.json"), JSON.stringify(summary, null, 2));
console.log("wrote evidence/summary.json");
